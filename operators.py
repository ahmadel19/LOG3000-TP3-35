"""Module contenant les fonctions 
d'opérations mathématiques pour la calculatrice.

"""
def add(a,b):
    """
    Additionne deux nombres.
    Paramètres:
        a (float): Le premier nombre.
        b (float): Le second nombre.
    Return:
        float: La somme des deux nombres.

    """
    return a + b

def subtract(a,b):
    """
    Soustrait le second nombre du premier.
    Paramètres:
        a (float): Le premier nombre.
        b (float): Le second nombre.
    Return:
        float: La différence des deux nombres.

    """
    return b - a

def multiply(a,b):
    """
    Multiplie deux nombres.
    Paramètres:
        a (float): Le premier nombre.
        b (float): Le second nombre.
    Return:
        float: Le produit des deux nombres.

    """
    return a * b

def divide(a,b):
    """
    Divise le premier nombre par le second.
    Paramètres:
        a (float): Le premier nombre.
        b (float): Le second nombre.
    Return:
        float: Le quotient des deux nombres.

    """
    return a / b
